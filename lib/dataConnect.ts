/**
 * Firebase Data Connect Setup
 * Initializes connection to Firebase SQL (PostgreSQL)
 * 
 * Environment variables required:
 * - NEXT_PUBLIC_DATA_CONNECT_PROJECT_ID
 * - NEXT_PUBLIC_DATA_CONNECT_SERVICE_ID
 * - NEXT_PUBLIC_DATA_CONNECT_LOCATION
 * 
 * NOTE: Data Connect is OPTIONAL. The app falls back to localStorage for all data operations.
 * To enable Data Connect:
 * 1. Set up Data Connect in Firebase Console
 * 2. Run: firebase dataconnect:build
 * 3. This generates the required connector file
 */

// Data Connect is optional - if initialization fails, we use localStorage
let dataConnectInitialized = false;
let dataConnectAvailable = false;

/**
 * Initialize Data Connect (called once on app startup)
 * Safe to fail - the app will work with localStorage
 */
export function initializeDataConnect() {
  if (dataConnectInitialized) return;
  dataConnectInitialized = true;

  try {
    const projectId = process.env.NEXT_PUBLIC_DATA_CONNECT_PROJECT_ID;
    const serviceId = process.env.NEXT_PUBLIC_DATA_CONNECT_SERVICE_ID;
    const location = process.env.NEXT_PUBLIC_DATA_CONNECT_LOCATION;
    
    if (!projectId || !serviceId || !location) {
      console.log('Data Connect not configured. Using localStorage for data storage.');
      return;
    }

    // Try to use Data Connect if available
    try {
      require('@firebase/data-connect');
      dataConnectAvailable = true;
      console.log('Data Connect available - will use SQL when configured in Firebase Console');
    } catch {
      console.log('Data Connect SDK not ready - using localStorage for data storage');
    }
  } catch (error) {
    // Silently fail - localStorage will be used as fallback
  }
}

/**
 * Check if Data Connect is available
 */
export function isDataConnectAvailable(): boolean {
  return dataConnectAvailable;
}


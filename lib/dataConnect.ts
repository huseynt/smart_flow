/**
 * Utility to handle Data Connect errors
 * Maps Data Connect errors to user-friendly Azerbaijani messages
 */
export function handleDataConnectError(error: any): string {
  const message = error?.message || 'Verilənlər bazasına bağlantı xətası';
  
  // Map specific errors to user-friendly messages in Azerbaijani
  if (message.includes('ALREADY_EXISTS')) {
    return 'Bu element artıq mövcuddur';
  }
  if (message.includes('NOT_FOUND')) {
    return 'Element tapılmadı';
  }
  if (message.includes('PERMISSION_DENIED')) {
    return 'Bu əməliyyatı yerinə yetirmək üçün icazəniz yoxdur';
  }
  if (message.includes('INVALID_ARGUMENT')) {
    return 'Düzgün olmayan arqument göndərildi';
  }
  if (message.includes('UNAVAILABLE')) {
    return 'Verilənlər bazası hazırda əlçatışmaz';
  }
  
  return message;
}

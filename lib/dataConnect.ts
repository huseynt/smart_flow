/**
 * Execute Data Connect query
 * Returns null if Data Connect not available - caller will use localStorage
 */
export async function executeQuery<T>(
  query: any,
  variables?: Record<string, any>
): Promise<T | null> {
  if (!isDataConnectAvailable()) {
    return null;
  }
  
  try {
    const { execute } = require('@firebase/data-connect');
    const dataConnect = getDataConnectInstance();
    
    if (!dataConnect) {
      return null;
    }
    
    console.log('Executing Data Connect query:', { variables });
    const result = await execute(dataConnect, query, variables);
    console.log('Query result:', result.data);
    
    return result.data as T;
  } catch (error) {
    console.warn('Data Connect query error (using localStorage):', error);
    return null;
  }
}

